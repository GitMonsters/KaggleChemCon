"""Pack the dfthc-refit modules into one Kaggle script kernel (`kaggle/run.py`).

The kernel writes the modules to /kaggle/working/dfthc_refit/ and runs the given jobs there,
one per GPU at a time (Kaggle's GPU machines have two T4s), prefixing each job's output.

    python notebooks/dfthc-refit/make_kernel.py --job "run.py recipes/merged_10x120x60.toml"
    python notebooks/dfthc-refit/make_kernel.py --job "middle.py 12 120 60 --merge 2 ;; quantize.py ..." --job "..."
    kaggle kernels push -p notebooks/dfthc-refit/kaggle

The recipes in `recipes/` are shipped too. Set the kernel id in `kaggle/kernel-metadata.json`
(`--id`) to your own account.
"""
import argparse
import base64
import json
import shlex
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULES = ['paths.py', 'encode.py', 'public_seed.py', 'landscape4.py', 'structure.py', 'refine.py',
           'middle.py', 'quantize.py', 'polish_words.py', 'refit_weights.py', 'build.py', 'fourqrom.py', 'tensorqrom.py', 'onebody.py', 'lbfgs_fit.py', 'run.py']

ap = argparse.ArgumentParser()
ap.add_argument('--job', action='append', required=True,
                help='a module and its arguments; "a ;; b" runs b after a on the same GPU')
ap.add_argument('--embed', action='append', default=[], type=Path,
                help='a small input file, written to inputs/<name> next to the modules')
ap.add_argument('--id', default='marculera/dfthc-refit-gpu-sweep', help='the private kernel to push to')
args = ap.parse_args()
jobs = [[shlex.split(c) for c in j.split(';;')] for j in args.job]
sources = {m: (HERE / m).read_text() for m in MODULES}
sources |= {f'recipes/{r.name}': r.read_text() for r in sorted((HERE / 'recipes').glob('*.toml'))}
embedded = {f.name: base64.b64encode(f.read_bytes()).decode() for f in args.embed}

run = f'''# Generated by notebooks/dfthc-refit/make_kernel.py; edit the modules there, not this file.
import base64, concurrent.futures, json, os, queue, subprocess, sys
from pathlib import Path

try:
    import optax  # noqa: F401
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "optax"], check=True)
smi = subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True).stdout
print(smi, flush=True)
gpus = [str(i) for i, line in enumerate(smi.splitlines()) if line.startswith("GPU")] or [None]

SRC = Path("/kaggle/working/dfthc_refit")
SRC.mkdir(parents=True, exist_ok=True)
for name, text in json.loads({json.dumps(json.dumps(sources))}).items():
    (SRC / name).parent.mkdir(parents=True, exist_ok=True)
    (SRC / name).write_text(text)
(SRC / "inputs").mkdir(exist_ok=True)
for name, data in json.loads({json.dumps(json.dumps(embedded))}).items():
    (SRC / "inputs" / name).write_bytes(base64.b64decode(data))

free = queue.Queue()
for g in gpus:
    free.put(g)

def run(chain):
    gpu = free.get()
    env = dict(os.environ, **({{"CUDA_VISIBLE_DEVICES": gpu}} if gpu is not None else {{}}))
    try:
        for job in chain:
            tag = "[" + " ".join(job[:3]) + "]"
            # "@name" arguments are input files, wherever Kaggle mounted them under /kaggle/input.
            args = [next(Path("/kaggle/input").rglob(x[1:]), x) if x.startswith("@") else x for x in job[1:]]
            p = subprocess.Popen([sys.executable, "-u", str(SRC / job[0]), *map(str, args)], env=env,
                                 stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            for line in p.stdout:
                print(tag, line, end="", flush=True)
            if p.wait():
                return job, p.returncode
        return chain[-1], 0
    finally:
        free.put(gpu)

with concurrent.futures.ThreadPoolExecutor(len(gpus)) as pool:
    for job, code in pool.map(run, {jobs!r}):
        print("job", job, "exit", code, flush=True)
'''
(HERE / 'kaggle' / 'run.py').write_text(run)
(HERE / 'kaggle' / 'kernel-metadata.json').write_text(json.dumps({
    'id': args.id,
    'title': 'dfthc refit gpu sweep',
    'code_file': 'run.py',
    'language': 'python',
    'kernel_type': 'script',
    'is_private': True,
    'enable_gpu': True,
    'enable_internet': True,
    'dataset_sources': ['sohier/verifiable-circuit-compilation-starter-kit',
                        'dmitriigluzdov/vqcc-femoco-public-factorization',
                        'ahmedberatozer/df-thc-group-compression-factorization',
                        'marculera/dfthc-refit-structures'],
    'competition_sources': ['google-verifiable-quantum-circuit-compilation'],
    'kernel_sources': [],
}, indent=2) + '\n')
print('wrote', HERE / 'kaggle', 'jobs', jobs)
